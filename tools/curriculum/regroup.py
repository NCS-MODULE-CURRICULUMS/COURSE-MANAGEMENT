CSS = """  /* 업무 수행 단계 구분 줄 — 능력단위를 실제로 하는 차례로 묶어 둔다 */
  tr.grp td{background:#f2f2f2;border-top:2px solid #000;padding:9px 12px;text-align:left}
  tr.grp b{font-size:13.5px}
  tr.grp .gd{display:block;font-weight:400;font-size:11.5px;color:#555;margin-top:3px}
"""

NOTE = """
<div class="note"><b>차례</b><br>
능력단위를 <b>코드순이 아니라 실제로 하는 차례</b>로 묶었습니다 —
{flow} 입니다.<br>
묶음 안에서는 <b>수준이 낮은 것부터</b> 놓았습니다. 다만
<b>앞뒤가 이미 정해진 묶음</b>은 수준과 상관없이 <b>일하는 순서</b>를 따릅니다.<br>
<b>코드순으로 보려면</b> 코드 칸을 훑으십시오 — 코드는 그대로 두었습니다.</div>"""

MARK = "  /* 업무 수행 단계 구분 줄"
LABEL = "ABCDEFGHIJKLMN"


def level(row):
    return int(re.search(r"<td>(\d)</td>", row).group(1))


def rebuild(page, plan, check):
    s = page.read_text(encoding="utf-8")
    body = re.search(r"<tbody>(.*?)</tbody>", s, re.S).group(1)
    rows = re.findall(r'<tr><td class="nm">.*?</tr>', body, re.S)
    by_name = {re.search(r'<td class="nm">(.*?)</td>', r).group(1): r for r in rows}

    planned = [n for _, _, names, _ in plan for n in names]
    dup = {n for n in planned if planned.count(n) > 1}
    miss = [n for n in planned if n not in by_name]
    extra = sorted(set(by_name) - set(planned))
    if dup or miss or extra:
        print(f"  ✗ {page.name}")
        for n in sorted(dup):  print(f"     두 번 적음: {n}")
        for n in miss:         print(f"     표에 없음:  {n}")
        for n in extra:        print(f"     빠뜨림:     {n}")
        return False
    if check:
        print(f"  · {page.name:30} 능력단위 {len(planned):3} · 묶음 {len(plan)}")
        return True

    out, titles = [], []
    for i, (title, desc, names, seq) in enumerate(plan):
        picked = names if seq else sorted(names, key=lambda n: (level(by_name[n]),
                                                               names.index(n)))
        lv = "·".join(str(level(by_name[n])) for n in picked)
        tail = " · 앞뒤가 정해진 묶음" if seq and len(picked) > 1 else ""
        titles.append(f"{LABEL[i]} {title}")
        out.append(f'<tr class="grp"><td colspan="7"><b>{LABEL[i]}. {title}</b>'
                   f'<span class="gd">{desc} · 수준 {lv}{tail}</span></td></tr>')
        out += [by_name[n] for n in picked]

    # 여러 번 돌려도 되게 — 이미 든 것을 걷어 내고 다시 넣는다
    s = re.sub(r"<tbody>.*?</tbody>",
               "<tbody>\n" + "\n".join(out) + "\n</tbody>", s, count=1, flags=re.S)
    if MARK not in s:
        s = s.replace("</style>", CSS + "</style>", 1)
    s = re.sub(r"\n<div class=\"note\"><b>차례</b>.*?</div>", "", s, flags=re.S)
    note = NOTE.format(flow=" → ".join(f"<b>{t}</b>" for t in titles))
    anchor = re.search(r"(<div class=\"note\"><b>읽는 법</b>.*?</div>)", s, re.S)
    s = s[:anchor.end()] + "\n" + note + s[anchor.end():]

    page.write_bytes(s.encode("utf-8"))
    print(f"  ✓ {page.name:30} 능력단위 {len(planned):3} · 묶음 {len(plan)}")
    return True


def main():
    check = "--check" in sys.argv
    ok = tot = 0
    for key, plan in sorted(PLANS.items()):
        page = CUR / f"{key}.html"
        if not page.exists():
            print(f"  ✗ {page.name} 이 없습니다")
            continue
        tot += sum(len(n) for _, _, n, _ in plan)
        ok += rebuild(page, plan, check)
    print(f"\n세분류 {ok}/{len(PLANS)} · 능력단위 {tot}")
    return 0 if ok == len(PLANS) else 1


sys.exit(main())
